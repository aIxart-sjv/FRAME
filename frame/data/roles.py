"""Dataset roles and profiles (Phase 3).

One `DatasetProfile` per dataset FRAME knows about, holding what is DOCUMENTED about it:
its role, whether its pairs are synthetic or real, which splits it may appear in, its
bands, resolutions and scale factors, and its licence. QC checks every manifest record
against its profile, so a rule like "SEN2NEON is never training data" is enforced, not
merely written down.

Sources
-------
* Roles and tiers: docs/Requirements 142.txt, Requirement 3 sections 24-28 and 35-36
  (lines 3181-3526) and the dataset hierarchy at lines 3873-3906 and 11477-11501:

      TRAIN        SEN2NAIPv2 (synthetic, primary)   + SEN2VENuS (supplementary)
      VALIDATION   SEN2NAIPv2 cross-sensor
      FINAL TEST   SEN2NEON (12-band, 2.5 m)  +  OpenSR-Test  +  Indian holdout

* Per-dataset facts (bands, sizes, scales, licences) were checked against the datasets'
  own published cards during Phase 3, not only the requirements document:
    - SEN2NAIPv2  huggingface.co/datasets/tacofoundation/SEN2NAIPv2  (card, 2025-02-01)
    - SEN2NEON    huggingface.co/datasets/isp-uv-es/SEN2NEON          (card + metadata.csv)
    - SEN2VENuS   zenodo.org/records/14603764                          (record description)
    - OpenSR-Test the existing adapter, frame/validation/opensr_test_adapter.py

Where the requirements and a dataset card differ (patch sizes: the requirements speak of
128 / 512 model tiles, SEN2NAIPv2 ships 130 / 520 pixel patches), the profile records the
dataset's own facts and the patch extractor bridges the two.

`status` says honestly how far each dataset is implemented in FRAME right now.
"""

from __future__ import annotations

from dataclasses import dataclass
