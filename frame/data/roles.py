STATUS_REAL = "implemented: real data read and tested"
STATUS_FIXTURE = "implemented against the documented format; tested on synthetic fixtures only, no real data read"
STATUS_PLANNED = "planned: profile only, no data and no reader"
STATUS_SYNTHETIC = "generated by FRAME: synthetic scenes for smoke tests, no real imagery"


@dataclass(frozen=True)
class VariantSpec:
    """One coherent way a dataset is used: bands, scale, sizes, role."""

    name: str
    role: DatasetRole
    pair_type: PairType
    allowed_splits: FrozenSet[Split]
    lr_bands: Tuple[str, ...]
    hr_bands: Tuple[str, ...]
    scale_factor: int
    lr_pixel_size_m: Optional[float]
    hr_pixel_size_m: Optional[float]
    lr_size: Optional[Tuple[int, int]] = None      # (height, width) of one source tile
    hr_size: Optional[Tuple[int, int]] = None
    reflectance_scale: Optional[float] = 10_000.0
    notes: str = ""


@dataclass(frozen=True)
class DatasetProfile:
    dataset: str
    title: str
    variants: Mapping[str, VariantSpec]
    scene_unit: str                 # what a scene_id means here: the unit that must never span two splits
    region_unit: Optional[str]      # what a region_id means here
    license: str
    status: str
    source: str
    requirements_ref: str
    caveats: Tuple[str, ...] = ()

    def variant(self, name: str) -> VariantSpec:
        try:
            return self.variants[name]
        except KeyError:
            raise ContractError(
                f"{self.dataset} has no variant {name!r}; known: {sorted(self.variants)}.", code="unknown_variant"
            ) from None


def _v(**kw) -> VariantSpec:
    return VariantSpec(**kw)


