def get_profile(dataset: str) -> DatasetProfile:
    try:
        return DATASET_PROFILES[dataset]
    except KeyError:
        raise ContractError(f"Unknown dataset {dataset!r}; known: {sorted(DATASET_PROFILES)}.", code="unknown_dataset") from None
